import { createRequire } from 'node:module';
import { readFile, writeFile, copyFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const require = createRequire(import.meta.url);
const source = dirname(require.resolve('lucide-static/package.json'));
const output = resolve(import.meta.dirname, '../public/assets');
const { version } = JSON.parse(await readFile(resolve(source, 'package.json'), 'utf8'));
// Keep the existing action IDs so callers and tooltips retain their behavior.
const icons = {
  download: 'download', device: 'send', play: 'play', stop: 'square',
  scan: 'refresh-cw', settings: 'settings-2', search: 'search',
  headphones: 'headphones', music: 'music', plus: 'plus',
  close: 'x', chevron: 'chevron-right', edit: 'pencil',
};
const symbols = [];
for (const [id, name] of Object.entries(icons)) {
  const file = await readFile(resolve(source, `icons/${name}.svg`), 'utf8');
  const body = file.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)?.[1];
  if (!body) throw new Error(`Cannot extract Lucide icon: ${name}`);
  symbols.push(`<symbol id="${id}" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body.trim()}</g></symbol>`);
}
const sprite = `<!-- Lucide ${version}. License: lucide-license.txt. Generated by pnpm icons:build. -->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`;
await writeFile(resolve(output, 'song-actions.svg'), sprite);
await copyFile(resolve(source, 'LICENSE'), resolve(output, 'lucide-license.txt'));
console.log(`Lucide ${version}: ${symbols.length} local SVG icons, ${Buffer.byteLength(sprite)} bytes.`);
